/**
 * Roux 과정. 글과 예시 상태만 담는다 (화면에 올릴 큐브와 동작은 resolve.ts가 만든다).
 *
 * 손으로 만든 예시는 모두 "목표가 이루어진 상태에 보여 줄 동작을 거꾸로 적용한 상태"에서 시작한다.
 * 그래서 동작을 다 하면 반드시 목표 상태가 된다. 글에 적은 조각 위치와 결과는 rouxCourse.test.ts가 확인한다.
 */
import { CMLL_CASES } from '../../algorithms/cmll';
import { algToString, invertAlg, parseAlg } from '../../core/notation';
import type { Course, LessonStep } from './courses';

const inv = (alg: string) => algToString(invertAlg(parseAlg(alg)));

/**
 * 여러 단계로 이어지는 예시의 i번째 단계가 시작하는 모습.
 * goal(끝났을 때의 모습을 만드는 동작)에서 i번째 이후의 동작을 모두 거꾸로 적용한다.
 */
const startOf = (goal: string, parts: readonly string[], i: number) =>
  `${goal} ${inv(parts.slice(i).join(' '))}`.trim();

// 강조할 조각. 이름은 완성 상태(흰색 위) 기준이라, 노란색을 위로 잡으면 위아래와 좌우가 바뀐다.
/** 잡았을 때 왼쪽 아래 두 층: 빨간 센터와 조각 5개 */
const LEFT_BLOCK = 'R UR FR BR UFR UBR';
/** 잡았을 때 오른쪽 아래 두 층: 주황 센터와 조각 5개 */
const RIGHT_BLOCK = 'L UL FL BL UFL UBL';
const BLOCKS = `${LEFT_BLOCK} ${RIGHT_BLOCK}`;
/** 잡았을 때 윗층 코너 4개 */
const TOP_CORNERS = 'DFR DFL DBR DBL';
const CMLL_FOCUS = `${BLOCKS} ${TOP_CORNERS}`;
/** 잡았을 때 가운데 줄: 센터 4개와 엣지 4개 */
const M_SLICE = 'U D F B UF UB DF DB';
/** 잡았을 때 윗층 왼쪽·오른쪽 엣지 (노랑-빨강, 노랑-주황) */
const SIDE_EDGES = 'DL DR';
const LSE_FOCUS = `${M_SLICE} ${SIDE_EDGES}`;

// ───────── 첫 번째 블록 예시 ─────────
/** 예시 1: 사각형(아래 엣지 + 뒤쪽 짝) → 앞쪽 짝 */
const FB_SQUARE_THEN_PAIR = ["D2 B' U' B", "F U F'"] as const;
/** 예시 2: 가운데 줄의 엣지를 M으로 꺼내 오는 경우. 끝나면 가운데 줄이 M만큼 돌아가 있다. */
const FB_WITH_M = ["D' M F' U' B"] as const;

// ───────── 두 번째 블록 예시 ─────────
/** 예시 1: 아래 엣지 → 뒤쪽 짝 → 앞쪽 짝. 끝나면 가운데 줄이 M'만큼 돌아가 있다. */
const SB_THREE_PARTS = ["M' U' R2", "R' U R", "U R U' R'"] as const;
/** 예시 2: 엣지가 가운데 줄에 있을 때 */
const SB_WIDE = "r U' r'";

// ───────── CMLL 예시 ─────────
/** 코너와 블록은 그대로 두고 엣지 6개만 모두 섞는다 (M은 합쳐서 한 바퀴, U는 합쳐서 제자리라 센터와 코너는 그대로다). */
const EDGES_MIXED = "M U M2 U' M";
const cmll = (id: string) => CMLL_CASES.find((c) => c.id === id)!;

/** CMLL 공식 하나를 보여 주는 단계: 공식을 하고 나면 코너는 맞고 엣지는 섞여 있다. */
const cmllStep = (id: string, lead: string, body: string[]): LessonStep => ({
  title: `예시: ${cmll(id).name} (${lead})`,
  body: [...body, `공식: ${cmll(id).alg}`],
  setup: `${EDGES_MIXED} ${inv(cmll(id).alg)}`,
  alg: cmll(id).alg,
  focus: CMLL_FOCUS,
});

// ───────── LSE 예시 ─────────
